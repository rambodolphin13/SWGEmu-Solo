function DecorVendor:start()
end

function DecorVendor:openCategoryMenu(pPlayer, pNpc)
	if (pPlayer == nil) then
		return
	end

	local sui = SuiListBox.new("DecorVendor", "handleCategorySelection")
	sui.setTargetNetworkId(SceneObject(pNpc):getObjectID())
	sui.setTitle("Furniture Dealer")
	sui.setPrompt("Choose a decor or furniture category.")

	for i = 1, #self.categories, 1 do
		sui.add(self.categories[i].name, tostring(i - 1))
	end

	sui.sendTo(pPlayer)
end

function DecorVendor:handleCategorySelection(pPlayer, pSui, eventIndex, args)
	if (pPlayer == nil or args == nil or args == "") then
		return
	end

	local selectedIndex = tonumber(args)

	if (selectedIndex == nil) then
		CreatureObject(pPlayer):sendSystemMessage("Invalid decor category selection.")
		return
	end

	local categoryIndex = selectedIndex + 1

	if (self.categories[categoryIndex] == nil) then
		CreatureObject(pPlayer):sendSystemMessage("Invalid decor category.")
		return
	end

	self:openItemGroupMenu(pPlayer, categoryIndex)
end

function DecorVendor:openItemGroupMenu(pPlayer, categoryIndex)
	if (pPlayer == nil or categoryIndex == nil) then
		return
	end

	local category = self.categories[categoryIndex]

	if (category == nil) then
		CreatureObject(pPlayer):sendSystemMessage("Invalid decor category.")
		return
	end

	local itemCount = #category.items
	local pageSize = 20

	if (itemCount <= pageSize) then
		self:openItemMenu(pPlayer, categoryIndex, 1, itemCount)
		return
	end

	writeData(SceneObject(pPlayer):getObjectID() .. ":decorVendorCategory", categoryIndex)

	local sui = SuiListBox.new("DecorVendor", "handleItemGroupSelection")
	sui.setTitle(category.name)
	sui.setPrompt("Choose an item group.")

	local startIndex = 1

	while (startIndex <= itemCount) do
		local endIndex = startIndex + pageSize - 1

		if (endIndex > itemCount) then
			endIndex = itemCount
		end

		sui.add("Items " .. startIndex .. "-" .. endIndex, tostring(startIndex - 1))
		startIndex = endIndex + 1
	end

	sui.sendTo(pPlayer)
end

function DecorVendor:handleItemGroupSelection(pPlayer, pSui, eventIndex, args)
	if (pPlayer == nil or args == nil or args == "") then
		return
	end

	local categoryIndex = readData(SceneObject(pPlayer):getObjectID() .. ":decorVendorCategory")

	if (categoryIndex == nil or categoryIndex == 0 or self.categories[categoryIndex] == nil) then
		CreatureObject(pPlayer):sendSystemMessage("Invalid decor category.")
		return
	end

	local selectedStart = tonumber(args)

	if (selectedStart == nil) then
		CreatureObject(pPlayer):sendSystemMessage("Invalid decor item group selection.")
		return
	end

	local startIndex = selectedStart + 1
	local endIndex = startIndex + 19

	if (endIndex > #self.categories[categoryIndex].items) then
		endIndex = #self.categories[categoryIndex].items
	end

	self:openItemMenu(pPlayer, categoryIndex, startIndex, endIndex)
end

function DecorVendor:openItemMenu(pPlayer, categoryIndex, startIndex, endIndex)
	if (pPlayer == nil) then
		return
	end

	local category = self.categories[categoryIndex]

	if (category == nil) then
		CreatureObject(pPlayer):sendSystemMessage("Invalid decor category.")
		return
	end

	if (startIndex == nil) then
		startIndex = 1
	end

	if (endIndex == nil or endIndex > #category.items) then
		endIndex = #category.items
	end

	writeData(SceneObject(pPlayer):getObjectID() .. ":decorVendorCategory", categoryIndex)

	local sui = SuiListBox.new("DecorVendor", "handleItemSelection")
	sui.setTitle(category.name)
	sui.setPrompt("Select an item to buy. Prices are shown beside each item.")

	for i = startIndex, endIndex, 1 do
		local item = category.items[i]
		sui.add(item.name .. " - " .. item.price .. " credits", tostring(i - 1))
	end

	sui.sendTo(pPlayer)
end

function DecorVendor:handleItemSelection(pPlayer, pSui, eventIndex, args)
	if (pPlayer == nil or args == nil or args == "") then
		return
	end

	local categoryIndex = readData(SceneObject(pPlayer):getObjectID() .. ":decorVendorCategory")
	deleteData(SceneObject(pPlayer):getObjectID() .. ":decorVendorCategory")

	if (categoryIndex == nil or categoryIndex == 0 or self.categories[categoryIndex] == nil) then
		CreatureObject(pPlayer):sendSystemMessage("Invalid decor category.")
		return
	end

	local selectedIndex = tonumber(args)

	if (selectedIndex == nil) then
		CreatureObject(pPlayer):sendSystemMessage("Invalid decor item selection.")
		return
	end

	local itemIndex = selectedIndex + 1
	local category = self.categories[categoryIndex]

	if (category.items[itemIndex] == nil) then
		CreatureObject(pPlayer):sendSystemMessage("Invalid decor item.")
		return
	end

	self:buyItem(pPlayer, category.items[itemIndex])
end

function DecorVendor:buyItem(pPlayer, item)
	if (pPlayer == nil or item == nil) then
		return
	end

	local pInventory = SceneObject(pPlayer):getSlottedObject("inventory")

	if (pInventory == nil) then
		CreatureObject(pPlayer):sendSystemMessage("Unable to locate your inventory.")
		return
	end

	if (SceneObject(pInventory):isContainerFullRecursive()) then
		CreatureObject(pPlayer):sendSystemMessage("Your inventory is full.")
		return
	end

	local price = item.price or 0

	if (CreatureObject(pPlayer):getCashCredits() < price) then
		CreatureObject(pPlayer):sendSystemMessage("You need " .. price .. " credits to buy this item.")
		return
	end

	local pItem = giveItem(pInventory, item.template, -1, true)

	if (pItem == nil) then
		CreatureObject(pPlayer):sendSystemMessage("Unable to create item: " .. item.template)
		return
	end

	CreatureObject(pPlayer):subtractCashCredits(price)
	CreatureObject(pPlayer):sendSystemMessage("Purchased: " .. item.name .. " for " .. price .. " credits.")
end
