function StructureDeedVendor:spawnVendor(planet, x, z, y, heading, cellID)
	local pNpc = spawnMobile(planet, "structure_deed_vendor", 0, x, z, y, heading, cellID or 0)
	if (pNpc ~= nil) then
		CreatureObject(pNpc):setOptionsBitmask(264)
		CreatureObject(pNpc):setCustomObjectName("Structure Deed Vendor")
	end
	return pNpc
end

function StructureDeedVendor:openCategoryMenu(pPlayer, pNpc)
	if (pPlayer == nil) then
		return
	end

	local sui = SuiListBox.new("StructureDeedVendor", "categoryCallback")
	sui.setTitle("Structure Deed Vendor")
	sui.setPrompt("Choose a deed category. Standard deeds cost " .. self.price .. " credits. Special Houses cost 500000 credits. Deeds are created directly in your inventory.")

	for i = 1, #self.categories, 1 do
		sui.add(self.categories[i].name, tostring(i))
	end

	sui.sendTo(pPlayer)
end

function StructureDeedVendor:categoryCallback(pPlayer, pSui, eventIndex, args)
	if (pPlayer == nil or eventIndex == 1 or args == nil or tonumber(args) == nil or tonumber(args) < 0) then
		return
	end

	local pPageData = LuaSuiBoxPage(pSui):getSuiPageData()
	if (pPageData == nil) then
		return
	end

	local categoryIndex = tonumber(LuaSuiPageData(pPageData):getStoredData(tostring(args)))
	if (categoryIndex == nil) then
		return
	end

	self:openDeedMenu(pPlayer, categoryIndex)
end

function StructureDeedVendor:openDeedMenu(pPlayer, categoryIndex)
	if (pPlayer == nil or categoryIndex == nil or self.categories[categoryIndex] == nil) then
		return
	end

	local category = self.categories[categoryIndex]
	local sui = SuiListBox.new("StructureDeedVendor", "deedCallback")
	sui.setTitle(category.name)
	sui.setPrompt("Select a deed to buy. Prices are shown beside each deed.")

	for i = 1, #category.deeds, 1 do
		local deedPrice = category.deeds[i].price or self.price
		sui.add(category.deeds[i].name .. " - " .. deedPrice .. " credits", tostring(categoryIndex) .. ":" .. tostring(i))
	end

	sui.sendTo(pPlayer)
end

function StructureDeedVendor:deedCallback(pPlayer, pSui, eventIndex, args)
	if (pPlayer == nil or eventIndex == 1 or args == nil or tonumber(args) == nil or tonumber(args) < 0) then
		return
	end

	local pPageData = LuaSuiBoxPage(pSui):getSuiPageData()
	if (pPageData == nil) then
		return
	end

	local storedData = LuaSuiPageData(pPageData):getStoredData(tostring(args))
	local categoryIndex, deedIndex = string.match(storedData, "(%d+):(%d+)")
	categoryIndex = tonumber(categoryIndex)
	deedIndex = tonumber(deedIndex)

	if (categoryIndex == nil or deedIndex == nil or self.categories[categoryIndex] == nil or self.categories[categoryIndex].deeds[deedIndex] == nil) then
		return
	end

	self:buyDeed(pPlayer, self.categories[categoryIndex].deeds[deedIndex])
end

function StructureDeedVendor:buyDeed(pPlayer, deed)
	if (pPlayer == nil or deed == nil) then
		return
	end

	local pInventory = CreatureObject(pPlayer):getSlottedObject("inventory")
	if (pInventory == nil) then
		CreatureObject(pPlayer):sendSystemMessage("Unable to find your inventory.")
		return
	end

	if (SceneObject(pInventory):isContainerFullRecursive()) then
		CreatureObject(pPlayer):sendSystemMessage("Your inventory is full.")
		return
	end

	local deedPrice = deed.price or self.price

	if (CreatureObject(pPlayer):getCashCredits() < deedPrice) then
		CreatureObject(pPlayer):sendSystemMessage("You need " .. deedPrice .. " credits to buy this deed.")
		return
	end

	local pItem = giveItem(pInventory, deed.template, -1, true)
	if (pItem == nil) then
		CreatureObject(pPlayer):sendSystemMessage("That deed template failed to create: " .. deed.template)
		return
	end

	CreatureObject(pPlayer):subtractCashCredits(deedPrice)
	CreatureObject(pPlayer):sendSystemMessage("Purchased: " .. deed.name .. " for " .. deedPrice .. " credits.")
end
